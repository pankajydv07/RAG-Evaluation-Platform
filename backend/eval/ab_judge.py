"""Head-to-Head Comparative LLM Judge for A/B model evaluation."""

import random
import time
from backend.providers.base import LLMProvider
from backend.schemas.ab_test import JudgeVerdict

COMPARATIVE_JUDGE_SYSTEM_PROMPT = """You are an expert impartial judge evaluating two candidate answers (Answer 1 and Answer 2) generated by different AI systems for a Retrieval-Augmented Generation (RAG) task.

You are given:
1. User Query
2. Retrieved Context Passages
3. Answer 1
4. Answer 2

Evaluate both answers strictly based on:
- **Faithfulness to Context**: Does the answer rely only on the provided context without hallucinating?
- **Completeness & Directness**: Does it fully answer the question without extraneous fluff?
- **Citation Accuracy**: Are factual claims accurately supported by the context passages?

You MUST respond strictly with a valid JSON object matching this schema:
{
  "winner": "1" | "2" | "tie",
  "answer_1_score": <float between 0.0 and 1.0>,
  "answer_2_score": <float between 0.0 and 1.0>,
  "critique": "<2-3 sentences explaining which answer was better and why>"
}"""


class ComparativeJudge:
    """Evaluates pairs of model responses with position de-biasing."""

    def __init__(self, judge_provider: LLMProvider):
        self.judge_provider = judge_provider

    async def evaluate_pair(
        self,
        query: str,
        context_texts: list[str],
        answer_a: str,
        answer_b: str,
        judge_model: str | None = None,
    ) -> JudgeVerdict:
        # Position de-biasing: randomly shuffle which model is presented as Answer 1 vs Answer 2
        swap_order = random.choice([True, False])
        first_answer = answer_b if swap_order else answer_a
        second_answer = answer_a if swap_order else answer_b

        context_formatted = "\n\n".join([f"[Passage {i+1}]: {t}" for i, t in enumerate(context_texts)])

        prompt = f"""--- USER QUERY ---
{query}

--- RETRIEVED CONTEXT ---
{context_formatted}

--- ANSWER 1 ---
{first_answer}

--- ANSWER 2 ---
{second_answer}

Provide your comparative evaluation in JSON format:"""

        start = time.perf_counter()
        raw_json = await self.judge_provider.generate_json(
            prompt=prompt,
            system_prompt=COMPARATIVE_JUDGE_SYSTEM_PROMPT,
            temperature=0.0,
            model=judge_model,
        )
        latency_ms = (time.perf_counter() - start) * 1000.0

        raw_winner = str(raw_json.get("winner", "tie")).lower().strip()
        ans1_score = float(raw_json.get("answer_1_score", 0.0))
        ans2_score = float(raw_json.get("answer_2_score", 0.0))
        critique = str(raw_json.get("critique", ""))

        # Unswap to map back to Model A and Model B
        if swap_order:
            model_a_score = ans2_score
            model_b_score = ans1_score
            if raw_winner == "1":
                actual_winner = "B"
            elif raw_winner == "2":
                actual_winner = "A"
            else:
                actual_winner = "tie"
        else:
            model_a_score = ans1_score
            model_b_score = ans2_score
            if raw_winner == "1":
                actual_winner = "A"
            elif raw_winner == "2":
                actual_winner = "B"
            else:
                actual_winner = "tie"

        return JudgeVerdict(
            winner=actual_winner,
            judge_model=judge_model or "default_judge",
            model_a_score=model_a_score,
            model_b_score=model_b_score,
            critique=critique,
            eval_latency_ms=latency_ms,
        )
